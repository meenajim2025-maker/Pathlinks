#!/usr/bin/env node
/**
 * Census of decision-tool specificity (RULE: instrument before fix; census, never sample).
 * Measures app/data/decision_tools_protocol.json and asserts against scripts/census-ceiling.json:
 * every "generic" metric may only fall. `--update-ceiling` lowers the ceiling to today's numbers.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const PROTO = path.join(ROOT, 'app', 'data', 'decision_tools_protocol.json');
const CEIL = path.join(__dirname, 'census-ceiling.json');
const REPORT = path.join(ROOT, 'docs', 'CENSUS.md');

const p = JSON.parse(fs.readFileSync(PROTO, 'utf8'));
const all = []; p.systems.forEach(s => s.tools.forEach(t => all.push({ ...t, _sys: s.name })));
const texts = t => (t.steps || []).flatMap(st => (st.options || []).map(o => o.guidance || ''));
const count = new Map(); all.forEach(t => texts(t).filter(g => g.length >= 80).forEach(g => count.set(g, (count.get(g) || 0) + 1)));
const sharedAll = n => all.filter(t => { const c = texts(t).filter(g => g.length >= 80).map(g => count.get(g)); return c.length && c.every(x => x >= n); }).length;
const doseRe = /\b(mg|micrograms|mcg|od|bd|tds|qds|once daily|twice daily)\b/i;
const m = {
  totalTools: all.length,
  uniquePlanTexts: count.size,
  sharedWith5plus: sharedAll(5),
  sharedWith20plus: sharedAll(20),
  noSpecificRef: all.filter(t => (t.niceRefs || []).filter(r => !/^(NICE CKS|Local formulary|BNF)$/.test(r)).length === 0).length,
  singleStep: all.filter(t => (t.steps || []).length === 1).length,
  withDose: all.filter(t => doseRe.test(texts(t).join(' '))).length,
  curated: all.filter(t => t.planSource === 'curated').length,
  curatedSignedOff: all.filter(t => t.planSource === 'curated' && t.curated && t.curated.reviewedBy && t.curated.reviewedBy !== 'TODO').length,
  fallbackPlans: all.filter(t => t.planSource === 'fallback').length,
  mergedGeneric: all.filter(t => t.planSource === 'merged-generic').length,
  mergedGenericCoveredTopics: all.filter(t => t.planSource === 'merged-generic').reduce((a, t) => a + (t.mergedCount || 1), 0),
};
const bySys = {}; p.systems.forEach(s => { bySys[s.name] = { tools: s.tools.length, curated: s.tools.filter(t => t.planSource === 'curated').length, fallback: s.tools.filter(t => t.planSource === 'fallback').length }; });

const lines = [`# Decision-tool census — ${new Date().toISOString().slice(0, 10)}`, '', 'Generated by `node scripts/census-specificity.js`. Do not edit by hand.', '',
  '| Metric | Value |', '|---|---|', ...Object.entries(m).map(([k, v]) => `| ${k} | ${v} |`), '',
  '## By system', '', '| System | Tools | Curated | Fallback plans |', '|---|---|---|---|',
  ...Object.entries(bySys).map(([k, v]) => `| ${k} | ${v.tools} | ${v.curated} | ${v.fallback} |`), ''];
fs.writeFileSync(REPORT, lines.join('\n'));
console.log(lines.slice(4).join('\n'));

const MUST_FALL = ['sharedWith5plus', 'sharedWith20plus', 'noSpecificRef', 'fallbackPlans', 'mergedGeneric', 'mergedGenericCoveredTopics'];
const MUST_RISE = ['curated', 'curatedSignedOff'];
if (process.argv.includes('--update-ceiling') || !fs.existsSync(CEIL)) {
  fs.writeFileSync(CEIL, JSON.stringify({ updated: new Date().toISOString().slice(0, 10), ...m }, null, 2));
  console.log('\nCeiling written to scripts/census-ceiling.json');
  process.exit(0);
}
const ceil = JSON.parse(fs.readFileSync(CEIL, 'utf8'));
let bad = 0;
MUST_FALL.forEach(k => { if (m[k] > ceil[k]) { console.error(`✗ ${k}: ${m[k]} exceeds ceiling ${ceil[k]} — generic content was added`); bad++; } });
MUST_RISE.forEach(k => { if (m[k] < ceil[k]) { console.error(`✗ ${k}: ${m[k]} fell below floor ${ceil[k]} — curated content was lost`); bad++; } });
if (bad) process.exit(1);
console.log('\n✓ census within ceiling (scripts/census-ceiling.json)');
